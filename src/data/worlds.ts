export function getWorldById(id: string): World | undefined {
  return worlds.find((w) => w.id === id);
}

export function getStageById(stageId: string): { world: World; stage: (typeof worlds)[0]['stages'][0]; stageIndex: number } | undefined {
  for (const world of worlds) {
    const idx = world.stages.findIndex((s) => s.id === stageId);
    if (idx !== -1) return { world, stage: world.stages[idx], stageIndex: idx };
  }
  return undefined;
}
